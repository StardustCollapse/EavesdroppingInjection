//Table 26 - 17. Format of the VM - Entry Interruption - Information Field
typedef union _INTERRUPTION_INFORMATION {
	struct __INTERRUPTION_INFORMATION {
		ULONG Vector : 8;
		//------------------------------
		ULONG InterruptionType : 3;
		//0 = External Interruption
		//1 = Reserved
		//2 = NMI
		//3 = Hardware Exception (#PF...)
		//4 = Software Interrupt (INT n)
		//5 = Privileged Software Exception (INT 1)
		//6 = Software Exception (INT3 or INTO)
		//7 = Other Event
		//------------------------------
		ULONG DeliverErrorCode : 1;
		ULONG Reserved : 19;
		ULONG Valid : 1;
	} Fields;
	ULONG Flags;
} INTERRUPT_INFORMATION, * PINTERRUPT_INFORMATION;

