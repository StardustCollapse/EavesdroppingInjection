#pragma once

#define IOCTL_HV_START \
CTL_CODE(FILE_DEVICE_UNKNOWN, 0x800, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_HV_STOP \
CTL_CODE(FILE_DEVICE_UNKNOWN, 0x801, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

#define IOCTL_HV_BENCHMARK \
CTL_CODE(FILE_DEVICE_UNKNOWN, 0x802, METHOD_BUFFERED, FILE_READ_DATA | FILE_WRITE_DATA)

typedef struct _KERNEL_BENCHMARK_REQUEST
{
	ULONG Iterations;
} KERNEL_BENCHMARK_REQUEST, *PKERNEL_BENCHMARK_REQUEST;

typedef struct _KERNEL_BENCHMARK_ITEM
{
	CHAR Name[64];
	ULONG64 MinCycles;
	ULONG64 AvgCycles;
	ULONG64 MaxCycles;
	ULONG64 TotalCycles;
} KERNEL_BENCHMARK_ITEM, *PKERNEL_BENCHMARK_ITEM;

typedef struct _KERNEL_BENCHMARK_RESPONSE
{
	ULONG Count;
	KERNEL_BENCHMARK_ITEM Items[8];
} KERNEL_BENCHMARK_RESPONSE, *PKERNEL_BENCHMARK_RESPONSE;
