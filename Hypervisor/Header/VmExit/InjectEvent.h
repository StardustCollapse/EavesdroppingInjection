#pragma once
#include <ntifs.h>

typedef union _INTERRUPT_INFO {
	struct __INT_INFO{
		ULONG Vector : 8;
		/*
			0 = Ext Int
			1 = Rsvd
			2 = NMI
			3 = Exception
			4 = Soft INT
			5 = Priv Soft Trap
			6 = Unpriv Soft Trap
			7 = Other
		*/
		ULONG InterruptType : 3;
		ULONG DeliverCode : 1;
		ULONG Reserved : 19;
		ULONG Valid : 1;
	} Fields;
	ULONG Flags;
} INTERRUPT_INFORMATION, * PINTERRUPT_INFORMATION;

